/** Retreat effectiveness: the same Old Road walk (reach Broken Causeway, then the Key Trial Watchpost) at four health thresholds and three doctrines.
 *  npx tsx tools/retreat-report.ts [--n 300]     writes docs/o1_slice/RETREAT_REPORT.md */
import { writeFileSync } from 'node:fs';
import { loadSim } from '../src/combat/loadSimNode';
import { defaultPlan, type ExpeditionPlan } from '../src/expedition/plan';
import { runExpedition } from '../src/expedition/run';
import type { SimDoctrine } from '../src/combat/simApi';

const i = process.argv.indexOf('--n'), N = i > 0 ? Number(process.argv[i + 1]) : 300;
const sim = loadSim();
const known = ['C0', 'O1', 'O2', 'O3', 'KT'];
const pct = (n: number) => `${(n / N * 100).toFixed(1)}%`;
const rows: string[] = [];
for (const doctrine of ['guarded', 'measured', 'pressing'] as SimDoctrine[]) for (const threshold of [0, 30, 50, 70]) {
  const plan: ExpeditionPlan = { ...defaultPlan(), doctrine, retreatHpPct: threshold, objectives: [{ id: 'a', kind: 'reach', room: 'O3' }, { id: 'b', kind: 'reach', room: 'KT' }] };
  let extracted = 0, complete = 0, died = 0, escaped = 0, lost = 0, secs = 0, retreats = 0;
  for (let seed = 1; seed <= N; seed++) {
    const { chronicle: c, result } = runExpedition(sim, { seed, level: 80, focus: 'balanced', plan, known });
    if (c.outcome === 'extracted') extracted++; else if (c.outcome === 'died') died++;
    if (c.outcome === 'extracted' && c.objectives.every(o => o.status === 'completed')) complete++;
    const dis = c.intent.find(x => x.text.startsWith('Disengage')), esc = c.intent.find(x => x.text.startsWith('Broke contact'));
    if (result.legs.some(l => l.result.escaped)) escaped++;
    if (dis && esc) { const h0 = Number(/health (\d+)%/.exec(dis.text)![1]), m = /health (\d+) of (\d+)/.exec(esc.text)!; lost += h0 - Math.round(Number(m[1]) / Number(m[2]) * 100); secs += (esc.tick - dis.tick) / 30; retreats++; }
  }
  rows.push(`| ${doctrine} | ${threshold === 0 ? 'off' : `below ${threshold}%`} | ${pct(extracted)} | ${pct(complete)} | ${pct(died)} | ${pct(escaped)} | ${retreats ? (lost / retreats).toFixed(1) : '-'} | ${retreats ? (secs / retreats).toFixed(1) : '-'} |`);
}
const out = `# Retreat report (M3a, trial settings)

Level 80 balanced, real health (90), ${N} seeds per row. Plan: reach Broken Causeway, then the Key Trial Watchpost, then home. Enemies stay in their room and reset when the adventurer leaves. Generated by \`npx tsx tools/retreat-report.ts\`. Not a balance target: it shows what a retreat does, so a retreat that is too safe is visible.

| Doctrine | Retreat | Extracted | All objectives done | Died | Escaped a fight | Health points lost during the retreat (avg) | Seconds from order to escape (avg) |
|---|---|---|---|---|---|---|---|
${rows.join('\n')}

Health points are percent of maximum health. "Escaped a fight" counts expeditions where the adventurer broke contact at least once.
`;
writeFileSync('docs/o1_slice/RETREAT_REPORT.md', out);
console.log(out);
