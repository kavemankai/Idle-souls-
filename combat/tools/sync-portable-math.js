// Pastes the portable-math block from combat/portable-math.js into every consumer.
//   node combat/tools/sync-portable-math.js          rewrite the copies
//   node combat/tools/sync-portable-math.js --check  exit 1 when a copy differs (CI)
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..', '..');
const OPEN = '// >>> portable-math', CLOSE = '// <<< portable-math';
const source = fs.readFileSync(path.join(root, 'combat/portable-math.js'), 'utf8');
const block = source.slice(source.indexOf(OPEN), source.indexOf(CLOSE) + CLOSE.length);
if (!block.startsWith(OPEN) || !block.endsWith(CLOSE)) throw new Error('markers missing in combat/portable-math.js');

function inSim(text) {
  const a = text.indexOf(OPEN), b = text.indexOf(CLOSE);
  if (a >= 0 && b > a) return text.slice(0, a) + block + text.slice(b + CLOSE.length);
  const anchor = "  'use strict';\n";
  const i = text.indexOf(anchor);
  if (i < 0) throw new Error("no 'use strict' anchor");
  return text.slice(0, i + anchor.length) + block + '\n' + text.slice(i + anchor.length);
}
const tsHeader = '// Generated by combat/tools/sync-portable-math.js from combat/portable-math.js. Do not edit.\n/* eslint-disable */\n// @ts-nocheck\n';
const tsFooter = `
export interface PortableMath {
  sin(x: number): number; cos(x: number): number; atan2(y: number, x: number): number;
  exp(x: number): number; hypot(x: number, y: number): number; pow(base: number, n: number): number;
}
export const portableMath: PortableMath = M;
`;
const targets = [
  { file: 'combat/deep-stats/combat-sim.js', make: inSim },
  { file: 'combat/main/combat-sim.js', make: inSim },
  { file: 'src/combat/portableMath.ts', make: () => tsHeader + block + '\n' + tsFooter },
];
let bad = 0;
for (const t of targets) {
  const f = path.join(root, t.file);
  const old = fs.existsSync(f) ? fs.readFileSync(f, 'utf8') : '';
  const next = t.make(old);
  if (process.argv.includes('--check')) { if (old !== next) { console.log('out of sync:', t.file); bad++; } }
  else if (old !== next) { fs.writeFileSync(f, next); console.log('updated', t.file); }
}
if (process.argv.includes('--check')) { console.log(bad ? `different ${bad}` : 'in sync'); process.exit(bad ? 1 : 0); }
